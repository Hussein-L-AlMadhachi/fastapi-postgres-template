-- psql also reads the PG* variables, so a plain `psql` works when .env uses those.

create table items (
    id bigint generated by default as identity primary key,
    name varchar(127) not null,
    description varchar(1024),
    price decimal(10,2) not null,
    tax decimal(10,2)
);

-- One table for every auth mode. At least one identity column must be set, so
-- password, email OTP and phone OTP accounts can all live side by side.
create table users (
    id bigint generated by default as identity primary key,

    username varchar(127) unique,
    phone_number varchar(31) unique,
    email varchar(511) unique,
    role varchar(32) not null default 'user',

    -- argon2id hashes are about 98 characters, so text is the safe choice.
    password_hash text,

    otp varchar(12),
    otp_expires_at TIMESTAMP,

    isdisabled boolean default false not null,

    created_at TIMESTAMP default now(),
    updated_at TIMESTAMP default now(),
    deleted_at TIMESTAMP default null,

    constraint users_identity_check check (
        username is not null
        or phone_number is not null
        or email is not null
    )
);
