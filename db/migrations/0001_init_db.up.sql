-- psql also reads the PG* variables, so a plain `psql` works when .env uses those.

create table users (
    id bigint generated by default as identity primary key,

    username varchar(127) unique,
    phone_number varchar(31) unique,
    email varchar(511) unique,
    role varchar(31) not null default 'user',

    password_hash text,

    otp varchar(12),
    otp_expires_at TIMESTAMP,

    isdisabled boolean default false not null,

    created_at TIMESTAMP default now(),
    updated_at TIMESTAMP default now(),
    deleted_at TIMESTAMP default null,

    constraint users_identity_check check (
        username is not null
        or phone_number is not null
        or email is not null
    )
);
